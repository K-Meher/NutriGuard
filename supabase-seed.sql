-- Supabase Setup Script for NutriGuard
-- Drops existing tables to ensure a clean slate
DROP TABLE IF EXISTS public.ingredient_evidence CASCADE;
DROP TABLE IF EXISTS public.ingredient_aliases CASCADE;
DROP TABLE IF EXISTS public.ingredients CASCADE;

CREATE TABLE public.ingredients (
    id SERIAL PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    category TEXT,
    health_impact TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

CREATE TABLE public.ingredient_aliases (
    id SERIAL PRIMARY KEY,
    ingredient_id INTEGER REFERENCES public.ingredients(id) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

CREATE TABLE public.ingredient_evidence (
    id SERIAL PRIMARY KEY,
    ingredient_id INTEGER REFERENCES public.ingredients(id) ON DELETE CASCADE,
    url TEXT NOT NULL,
    title TEXT,
    org TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

