const insertEv = db.prepare(`
  INSERT OR REPLACE INTO ingredient_evidence
    (evidence_id, ingredient_id, evidence_type, evidence_summary, source_organization, source_reference, official_source_url, official_detail_link, evidence_status, notes)
  VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
`);

const insertNorm = db.prepare(`
  INSERT OR REPLACE INTO ingredient_normalizations
    (mapping_id, ingredient_id, canonical_ingredient_name, raw_label_term, normalized_term, match_type, ins_number, ocr_variant, confidence, normalization_rule, notes)
  VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
`);

let normCounter = 15000;
db.transaction(() => {
  for (const item of dataset) {
    insertIng.run(
      item.id,
      item.name,
      item.aliases,
      item.ins,
      item.type,
      item.func,
      item.org,
      item.ref,
      item.url,
      item.detail_url
    );

    insertEv.run(
      `EV_${item.id}`,
      item.id,
      item.evidence_type,
      item.evidence_summary,
      item.org,
      item.ref,
      item.url,
      item.detail_url,
      item.evidence_status,
      item.notes
    );

    for (const term of item.mappings) {
      normCounter++;
      insertNorm.run(
        `NORM_${normCounter}`,
        item.id,
        item.name,
        term,
        term.toLowerCase(),
        term.startsWith("ins") || /^\d+/.test(term) ? "ins" : "alias",
        item.ins,
        null,
        "High",
        "Official Global Food Standard Mapping",
        item.notes
      );
    }
  }
})();

console.log(`Successfully seeded ${dataset.length} comprehensive global food ingredients with verified official links.`);
